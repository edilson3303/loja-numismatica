create table if not exists public.users(
  id bigint generated by default as identity primary key,
  email text not null unique,
  password_hash text not null,
  role text not null default 'admin' check(role in ('admin')),
  active boolean not null default true,
  totp_secret_enc text,
  totp_enabled boolean not null default false,
  failed_logins integer not null default 0,
  locked_until bigint not null default 0,
  last_login_at bigint,
  created_at bigint not null,
  updated_at bigint not null
);
create unique index if not exists users_email_lower_uq on public.users(lower(email));
create index if not exists users_active_idx on public.users(active,id);

create table if not exists public.sessions(
  token_hash text primary key,
  user_id bigint references public.users(id) on delete cascade,
  csrf_token text not null,
  created_at bigint not null,
  last_seen_at bigint not null,
  expires_at bigint not null,
  absolute_expires_at bigint not null,
  ip_hash text,
  ua_hash text,
  auth_stage text not null default 'anonymous' check(auth_stage in ('anonymous','password','authenticated'))
);
create index if not exists sessions_exp_idx on public.sessions(expires_at);
create index if not exists sessions_user_idx on public.sessions(user_id);

create table if not exists public.settings(
  key text primary key,
  value text not null,
  updated_at bigint not null
);

create table if not exists public.products(
  id bigint generated by default as identity primary key,
  name text not null,
  product_type text not null default 'moeda',
  product_type_label text not null default 'Moeda',
  origin text,
  era text not null default 'outro',
  era_label text not null default 'Outra / não se aplica',
  metal text not null default '',
  year text not null default '',
  denomination text,
  catalog_reference text,
  weight text,
  diameter text,
  grade text,
  price_cents bigint not null check(price_cents >= 0),
  legend text,
  description text,
  image_path text,
  stock integer not null default 1 check(stock >= 0),
  active boolean not null default true,
  version integer not null default 1,
  created_at bigint not null,
  updated_at bigint not null
);
create index if not exists products_active_idx on public.products(active,era,name);

create table if not exists public.product_images(
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  image_path text not null,
  position integer not null default 0,
  created_at bigint not null,
  unique(product_id,image_path)
);
create index if not exists product_images_product_idx on public.product_images(product_id,position,id);

create table if not exists public.orders(
  id bigint generated by default as identity primary key,
  public_id text not null unique,
  customer_name text not null,
  customer_phone text,
  customer_email text,
  note text,
  status text not null default 'pending' check(status in ('pending','awaiting_payment','paid','confirmed','preparing','shipped','delivered','completed','cancelled')),
  total_cents bigint not null,
  created_at bigint not null,
  updated_at bigint not null
);

create table if not exists public.order_items(
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint not null references public.products(id),
  product_name text not null,
  unit_price_cents bigint not null,
  quantity integer not null check(quantity > 0)
);
create index if not exists order_items_order_idx on public.order_items(order_id);

create table if not exists public.audit_logs(
  id bigint generated by default as identity primary key,
  user_id bigint references public.users(id) on delete set null,
  action text not null,
  entity text,
  entity_id text,
  ip_hash text,
  ua_hash text,
  details_json jsonb,
  created_at bigint not null
);
create index if not exists audit_created_idx on public.audit_logs(created_at desc);

