-- Plataforma multi-lojas
-- Execute UMA VEZ no Supabase > SQL Editor, ANTES de publicar a versão multi-lojas do código.
-- Em instalação nova: execute primeiro supabase/setup.sql e depois este arquivo.
--
-- Todos os dados existentes (produtos, pedidos, administradores, configurações)
-- passam a pertencer à loja nº 1 ("principal"). Nada é apagado.

begin;

-- ---------------------------------------------------------------------------
-- Lojas (clientes da plataforma)
-- ---------------------------------------------------------------------------
create table if not exists public.stores(
  id bigint generated by default as identity primary key,
  slug text not null unique check(slug ~ '^[a-z0-9](?:[a-z0-9-]{0,38}[a-z0-9])?$'),
  name text not null,
  custom_domain text unique,
  owner_name text,
  owner_email text,
  owner_phone text,
  document text,
  status text not null default 'active' check(status in ('active','suspended','cancelled')),
  plan_name text not null default 'Mensal',
  monthly_price_cents bigint not null default 0 check(monthly_price_cents >= 0),
  paid_until date not null default (current_date + 30),
  grace_days integer not null default 5 check(grace_days between 0 and 60),
  setup_token_hash text,
  notes text,
  created_at bigint not null,
  updated_at bigint not null
);
create index if not exists stores_status_idx on public.stores(status,paid_until);

insert into public.stores(id,slug,name,status,plan_name,monthly_price_cents,paid_until,created_at,updated_at)
values(1,'principal','Loja numismática','active','Loja própria',0,date '2099-12-31',
       (extract(epoch from clock_timestamp())*1000)::bigint,(extract(epoch from clock_timestamp())*1000)::bigint)
on conflict(id) do nothing;
select setval(pg_get_serial_sequence('public.stores','id'),greatest((select max(id) from public.stores),1));

-- ---------------------------------------------------------------------------
-- Administradores da plataforma (você) e mensalidades
-- ---------------------------------------------------------------------------
create table if not exists public.platform_users(
  id bigint generated by default as identity primary key,
  email text not null,
  password_hash text not null,
  active boolean not null default true,
  totp_secret_enc text,
  totp_enabled boolean not null default false,
  failed_logins integer not null default 0,
  locked_until bigint not null default 0,
  last_login_at bigint,
  created_at bigint not null,
  updated_at bigint not null
);
create unique index if not exists platform_users_email_lower_uq on public.platform_users(lower(email));

create table if not exists public.store_payments(
  id bigint generated by default as identity primary key,
  store_id bigint not null references public.stores(id) on delete restrict,
  amount_cents bigint not null check(amount_cents >= 0),
  paid_at date not null,
  months integer not null default 1 check(months between 1 and 36),
  method text,
  note text,
  previous_paid_until date,
  new_paid_until date not null,
  created_by bigint references public.platform_users(id) on delete set null,
  created_at bigint not null
);
create index if not exists store_payments_store_idx on public.store_payments(store_id,paid_at desc,id desc);

-- ---------------------------------------------------------------------------
-- store_id em todas as tabelas da loja
-- ---------------------------------------------------------------------------
alter table public.users      add column if not exists store_id bigint references public.stores(id) on delete restrict;
alter table public.settings   add column if not exists store_id bigint references public.stores(id) on delete restrict;
alter table public.products   add column if not exists store_id bigint references public.stores(id) on delete restrict;
alter table public.orders     add column if not exists store_id bigint references public.stores(id) on delete restrict;
alter table public.sessions   add column if not exists store_id bigint references public.stores(id) on delete cascade;
alter table public.audit_logs add column if not exists store_id bigint references public.stores(id) on delete set null;

update public.users      set store_id=1 where store_id is null;
update public.settings   set store_id=1 where store_id is null;
update public.products   set store_id=1 where store_id is null;
update public.orders     set store_id=1 where store_id is null;
update public.audit_logs set store_id=1 where store_id is null and action not like 'platform.%';
-- Sessões antigas não têm loja; serão recriadas no próximo acesso.
alter table public.sessions add column if not exists scope text not null default 'store';
delete from public.sessions where scope='store' and store_id is null;

alter table public.users    alter column store_id set not null;
alter table public.settings alter column store_id set not null;
alter table public.products alter column store_id set not null;
alter table public.orders   alter column store_id set not null;

-- Sessões da plataforma
alter table public.sessions add column if not exists platform_user_id bigint references public.platform_users(id) on delete cascade;
alter table public.sessions drop constraint if exists sessions_scope_check;
alter table public.sessions add constraint sessions_scope_check check(
  (scope='store' and store_id is not null and platform_user_id is null) or
  (scope='platform' and store_id is null and user_id is null)
);

alter table public.audit_logs add column if not exists platform_user_id bigint references public.platform_users(id) on delete set null;

-- E-mail de administrador passa a ser único POR LOJA.
alter table public.users drop constraint if exists users_email_key;
drop index if exists public.users_email_lower_uq;
create unique index if not exists users_store_email_lower_uq on public.users(store_id,lower(email));
create index if not exists users_store_idx on public.users(store_id,active,id);

-- Configurações por loja.
alter table public.settings drop constraint if exists settings_pkey;
alter table public.settings add primary key(store_id,key);

create index if not exists products_store_idx on public.products(store_id,active,name);
create index if not exists orders_store_idx on public.orders(store_id,created_at desc);
create index if not exists audit_store_idx on public.audit_logs(store_id,id desc);
create index if not exists sessions_store_idx on public.sessions(store_id);

-- ---------------------------------------------------------------------------
-- Segurança: o navegador nunca acessa as tabelas diretamente.
-- ---------------------------------------------------------------------------
alter table public.stores enable row level security;
alter table public.platform_users enable row level security;
alter table public.store_payments enable row level security;
revoke all on table public.stores,public.platform_users,public.store_payments from anon, authenticated;

-- Estatísticas por loja para o painel da plataforma.
create or replace view public.platform_store_stats as
select s.id as store_id,
  (select count(*) from public.products p where p.store_id=s.id) as products,
  (select count(*) from public.products p where p.store_id=s.id and p.active) as active_products,
  (select count(*) from public.orders o where o.store_id=s.id) as orders,
  (select coalesce(sum(o.total_cents),0) from public.orders o where o.store_id=s.id and o.status<>'cancelled') as revenue_cents,
  (select max(o.created_at) from public.orders o where o.store_id=s.id) as last_order_at,
  (select count(*) from public.users u where u.store_id=s.id) as admins,
  (select max(u.last_login_at) from public.users u where u.store_id=s.id) as last_admin_login_at
from public.stores s;
revoke all on public.platform_store_stats from anon, authenticated, public;
grant select on public.platform_store_stats to service_role;

-- ---------------------------------------------------------------------------
-- Funções transacionais com isolamento por loja
-- ---------------------------------------------------------------------------
drop function if exists public.create_order(text,text,text,text,text,jsonb);
drop function if exists public.change_order_status(bigint,text);
drop function if exists public.save_product(bigint,jsonb,jsonb);

create or replace function public.create_order(
  p_store_id bigint,
  p_public_id text,
  p_customer_name text,
  p_customer_phone text,
  p_customer_email text,
  p_note text,
  p_items jsonb
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_item jsonb;
  v_product public.products%rowtype;
  v_id bigint;
  v_qty integer;
  v_total bigint := 0;
  v_order_id bigint;
  v_now bigint := (extract(epoch from clock_timestamp()) * 1000)::bigint;
begin
  if p_store_id is null then raise exception 'INVALID_STORE'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 30 then
    raise exception 'INVALID_ORDER';
  end if;

  for v_item in select * from jsonb_array_elements(p_items)
  loop
    v_id := (v_item->>'id')::bigint;
    v_qty := (v_item->>'quantity')::integer;
    if v_qty < 1 or v_qty > 20 then raise exception 'INVALID_QTY'; end if;
    select * into v_product from public.products where id=v_id and store_id=p_store_id for update;
    if not found or not v_product.active then raise exception 'ITEM_UNAVAILABLE'; end if;
    if v_product.stock < v_qty then raise exception 'STOCK'; end if;
    v_total := v_total + (v_product.price_cents * v_qty);
  end loop;

  insert into public.orders(store_id,public_id,customer_name,customer_phone,customer_email,note,total_cents,created_at,updated_at)
  values(p_store_id,p_public_id,p_customer_name,nullif(p_customer_phone,''),nullif(p_customer_email,''),nullif(p_note,''),v_total,v_now,v_now)
  returning id into v_order_id;

  for v_item in select * from jsonb_array_elements(p_items)
  loop
    v_id := (v_item->>'id')::bigint;
    v_qty := (v_item->>'quantity')::integer;
    select * into v_product from public.products where id=v_id and store_id=p_store_id;
    update public.products set stock=stock-v_qty,version=version+1,updated_at=v_now where id=v_id and store_id=p_store_id;
    insert into public.order_items(order_id,product_id,product_name,unit_price_cents,quantity)
      values(v_order_id,v_id,v_product.name,v_product.price_cents,v_qty);
  end loop;

  return jsonb_build_object('id',v_order_id,'public_id',p_public_id,'total_cents',v_total);
end;
$$;

create or replace function public.change_order_status(p_store_id bigint,p_order_id bigint,p_status text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_line record;
  v_now bigint := (extract(epoch from clock_timestamp()) * 1000)::bigint;
begin
  if p_status not in ('pending','awaiting_payment','paid','confirmed','preparing','shipped','delivered','completed','cancelled') then raise exception 'INVALID_STATUS'; end if;
  select * into v_order from public.orders where id=p_order_id and store_id=p_store_id for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if v_order.status='cancelled' and p_status<>'cancelled' then raise exception 'FINAL'; end if;
  if v_order.status<>'cancelled' and p_status='cancelled' then
    for v_line in select product_id,quantity from public.order_items where order_id=p_order_id
    loop
      update public.products set stock=stock+v_line.quantity,version=version+1,updated_at=v_now
       where id=v_line.product_id and store_id=p_store_id;
    end loop;
  end if;
  update public.orders set status=p_status,updated_at=v_now where id=p_order_id and store_id=p_store_id;
  return jsonb_build_object('from_status',v_order.status,'to_status',p_status);
end;
$$;

create or replace function public.save_product(p_store_id bigint,p_id bigint,p_data jsonb,p_images jsonb)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
  v_img text;
  v_pos integer := 0;
  v_now bigint := (extract(epoch from clock_timestamp()) * 1000)::bigint;
begin
  if p_store_id is null then raise exception 'INVALID_STORE'; end if;
  if jsonb_typeof(coalesce(p_images,'[]'::jsonb)) <> 'array' or jsonb_array_length(coalesce(p_images,'[]'::jsonb)) > 12 then raise exception 'INVALID_IMAGES'; end if;
  if p_id is null then
    insert into public.products(store_id,name,product_type,product_type_label,origin,era,era_label,metal,year,denomination,catalog_reference,weight,diameter,grade,price_cents,legend,description,image_path,stock,active,created_at,updated_at)
    values(p_store_id,p_data->>'name',coalesce(nullif(p_data->>'product_type',''),'outro'),coalesce(nullif(p_data->>'product_type_label',''),'Outro item numismático'),nullif(p_data->>'origin',''),coalesce(nullif(p_data->>'era',''),'outro'),coalesce(nullif(p_data->>'era_label',''),'Outra / não se aplica'),coalesce(p_data->>'metal',''),coalesce(p_data->>'year',''),nullif(p_data->>'denomination',''),nullif(p_data->>'catalog_reference',''),p_data->>'weight',p_data->>'diameter',p_data->>'grade',(p_data->>'price_cents')::bigint,p_data->>'legend',p_data->>'description',nullif(p_data->>'image_path',''),(p_data->>'stock')::integer,coalesce((p_data->>'active')::boolean,true),v_now,v_now)
    returning id into v_id;
  else
    update public.products set
      name=p_data->>'name',product_type=coalesce(nullif(p_data->>'product_type',''),'outro'),product_type_label=coalesce(nullif(p_data->>'product_type_label',''),'Outro item numismático'),origin=nullif(p_data->>'origin',''),era=coalesce(nullif(p_data->>'era',''),'outro'),era_label=coalesce(nullif(p_data->>'era_label',''),'Outra / não se aplica'),metal=coalesce(p_data->>'metal',''),year=coalesce(p_data->>'year',''),denomination=nullif(p_data->>'denomination',''),catalog_reference=nullif(p_data->>'catalog_reference',''),
      weight=p_data->>'weight',diameter=p_data->>'diameter',grade=p_data->>'grade',price_cents=(p_data->>'price_cents')::bigint,
      legend=p_data->>'legend',description=p_data->>'description',image_path=nullif(p_data->>'image_path',''),stock=(p_data->>'stock')::integer,
      active=coalesce((p_data->>'active')::boolean,true),version=version+1,updated_at=v_now
    where id=p_id and store_id=p_store_id returning id into v_id;
    if v_id is null then raise exception 'NOT_FOUND'; end if;
    delete from public.product_images where product_id=v_id;
  end if;

  for v_img in select * from jsonb_array_elements_text(coalesce(p_images,'[]'::jsonb))
  loop
    if v_img !~ '^/media/[A-Za-z0-9_-]{10,120}\.webp$' then raise exception 'INVALID_IMAGE_PATH'; end if;
    insert into public.product_images(product_id,image_path,position,created_at) values(v_id,v_img,v_pos,v_now);
    v_pos := v_pos + 1;
  end loop;
  return v_id;
end;
$$;

